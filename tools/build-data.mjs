#!/usr/bin/env node
// Bundles data/map.json + data/routing.json + data/events.json into
// assets/js/data.js (window.AI4T_DATA). No runtime build: the site loads
// one script tag. Grids are RLE-packed strings to keep the file small.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const map = JSON.parse(readFileSync(join(root, 'data', 'map.json'), 'utf8'));
const routing = JSON.parse(readFileSync(join(root, 'data', 'routing.json'), 'utf8'));
const events = JSON.parse(readFileSync(join(root, 'data', 'events.json'), 'utf8'));
let routeOverrides = {};
let mainPath = {};
try { mainPath = JSON.parse(readFileSync(join(root, 'data', 'main-path.json'), 'utf8')); } catch (e) {}
try { routeOverrides = JSON.parse(readFileSync(join(root, 'data', 'route-overrides.json'), 'utf8')); } catch (e) {}

// ---- compact the map: drop labelPos/label for non-event rooms? Keep all (names used in
// print studio room picker). Round polygon coords to 1 decimal.
function roundPts(pts) { return pts.map(([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10]); }
const mapCompact = {};
for (const [f, fl] of Object.entries(map)) {
  mapCompact[f] = {
    buildings: fl.buildings.map(b => b.kind === 'poly'
      ? { id: b.id, letter: b.letter, pts: roundPts(b.pts) }
      : { id: b.id, letter: b.letter, x: b.x, y: b.y, w: b.w, h: b.h }),
    rooms: fl.rooms.map(r => ({
      id: r.id, name: r.name, type: r.type, acc: r.accessible || undefined,
      s: r.shapes.map(s => s.kind === 'poly' ? { p: roundPts(s.pts) } : { r: [s.x, s.y, s.w, s.h] }),
      c: r.centroid,
    })),
  };
}

// ---- RLE pack the routing grids: runs of 0/1/2 -> base36 pairs
function rle(arr) {
  const out = [];
  let cur = arr[0], n = 0;
  for (const v of arr) {
    if (v === cur) n++;
    else { out.push(cur.toString(36) + ':' + n.toString(36)); cur = v; n = 1; }
  }
  out.push(cur.toString(36) + ':' + n.toString(36));
  return out.join(',');
}
const routingCompact = {
  grid: routing.grid, w: routing.w, h: routing.h,
  floors: routing.floors, floorsOrderedTopDown: routing.floorsOrderedTopDown,
  grids: Object.fromEntries(routing.floors.map(f => [f, rle(routing.grids[f])])),
  anchors: routing.anchors,
  links: routing.links,
};

// event-relevant room index for quick lookup
const data = { map: mapCompact, routing: routingCompact, events, routeOverrides, mainPath };
const js = '// AUTO-GENERATED by tools/build-data.mjs — do not edit by hand.\n'
  + 'window.AI4T_DATA = ' + JSON.stringify(data) + ';\n';
mkdirSync(join(root, 'assets', 'js'), { recursive: true });
writeFileSync(join(root, 'assets', 'js', 'data.js'), js);
console.log('assets/js/data.js written:', (js.length / 1024).toFixed(0) + ' KB (raw), rooms:', Object.values(mapCompact).reduce((s, f) => s + f.rooms.length, 0));
